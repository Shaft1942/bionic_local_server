import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';
import { loadSettings } from '../lib/config.mjs';
import { createBionicStore } from '../lib/bionic-store.mjs';
import { runDiagnostics } from '../lib/diagnostics.mjs';
import { diagnoseLocalTransport } from '../lib/maintenance-client.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const settings=await loadSettings({root});
const result=await runDiagnostics({settings,checkCompanionTransport:()=>diagnoseLocalTransport({root,port:settings.port}),nativeStore:createBionicStore({root:settings.bionicRoot}),headers:()=>process.env.BIONIC_API_TOKEN?{Authorization:'Bearer '+process.env.BIONIC_API_TOKEN}:{}});
await writeFile(path.join(root,'diagnostic-bionic.json'),JSON.stringify(result,null,2)+'\n',{mode:0o600});
console.log(JSON.stringify(result,null,2));
console.log('Diagnostic en lecture seule : diagnostic-bionic.json. Aucun message ni modèle exécuté.');
