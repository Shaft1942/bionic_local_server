// Build-only tool. Runtime does not invoke npm or download any code.
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const buildDir = path.join(root, 'work/crypto-build');
const require = createRequire(path.join(buildDir, 'package.json'));
const { build } = require('esbuild');
const patches = [];
await mkdir(path.join(root, 'vendor'), { recursive: true });
const result = await build({
  stdin: { contents: "import 'reflect-metadata'; export * as x509 from '@peculiar/x509'; export * as pkijs from 'pkijs'; export * as asn1js from 'asn1js';", resolveDir: buildDir, sourcefile: 'certificate-vendor-entry.mjs' },
  bundle: true, platform: 'node', target: 'node24', format: 'esm', minify: true,
  legalComments: 'inline', outfile: path.join(root, 'vendor/certificate-crypto.mjs'), metafile: true,
  plugins: [{name:'windows-pkcs12-salt-interop',setup(builder) {
    builder.onLoad({filter:/[\\/]pkijs[\\/]build[\\/]index\.js$/},async args => {
      const original = await readFile(args.path,'utf8');
      if (createHash('sha256').update(original).digest('hex') !== '81323b7ffbe635d9fbfeef6cb6db6166c8c1a9ff6e4b1158a4c09515ab8c1685') throw new Error('Unexpected PKI.js source hash. Review upstream source and salt patch.');
      const anchor = original.indexOf('async encryptEncryptedContentInfo(parameters)');
      const salt = original.indexOf('new ArrayBuffer(64)',anchor);
      if (anchor < 0 || salt < 0 || salt > anchor + 1500 || require('pkijs/package.json').version !== '4.0.0') throw new Error('PKI.js source changed: review Windows salt interoperability patch before rebuilding.');
      const contents = original.slice(0,salt)+'new ArrayBuffer(16)'+original.slice(salt+'new ArrayBuffer(64)'.length);
      patches.push({id:'windows-pbes2-salt-128',package:'pkijs',version:'4.0.0',file:'build/index.js',description:'Only encryptEncryptedContentInfo PBKDF2 random salt length: 64 to 16 bytes. Windows native PFX import compatibility, verified by regression test.',sourceSha256:createHash('sha256').update(original).digest('hex'),patchedSha256:createHash('sha256').update(contents).digest('hex')});
      return {contents,loader:'js'};
    });
  }}],
});
const lock = JSON.parse(await readFile(path.join(buildDir, 'package-lock.json'), 'utf8'));
const packages = [];
let notices = '# Third party notices\n\nGenerated by scripts/build-crypto-vendor.mjs. Runtime cryptography dependencies are bundled in vendor/certificate-crypto.mjs.\n';
for (const [name, info] of Object.entries(lock.packages).filter(([name]) => name && !name.includes('esbuild'))) {
  const dir = path.join(buildDir, name);
  const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
  let license = '';
  for (const candidate of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'License.txt', 'LICENCE']) {
    try { license = await readFile(path.join(dir, candidate), 'utf8'); break; } catch {}
  }
  if (!license) throw new Error(`Missing license: ${pkg.name}`);
  packages.push({ name: pkg.name, version: pkg.version, integrity: info.integrity, resolved: info.resolved, license: pkg.license });
  notices += `\n## ${pkg.name} ${pkg.version} (${pkg.license})\n\n${license.trim()}\n`;
}
const bytes = await readFile(path.join(root, 'vendor/certificate-crypto.mjs'));
await writeFile(path.join(root, 'vendor/certificate-crypto.provenance.json'), JSON.stringify({ build: { esbuild: require('esbuild/package.json').version, node: process.versions.node }, sha256: createHash('sha256').update(bytes).digest('hex'), patches, packages }, null, 2) + '\n');
await writeFile(path.join(root, 'vendor/certificate-crypto.package-lock.json'), JSON.stringify(lock, null, 2) + '\n');
await writeFile(path.join(root, 'THIRD-PARTY-NOTICES.md'), notices);
console.log(`Bundled ${packages.length} dependency packages; ${bytes.length} bytes.`);
